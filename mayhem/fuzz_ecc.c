/* Elliptic-curve and finite-field Diffie-Hellman: ECDSA verify, ECDH (NIST curves, X25519/X448), DH group 2.
   Hostile peer public keys / signatures / hashes go straight into the verify and compute-secret paths. */
#include "common.h"
#include "nx_crypto_ecdsa.h"
#include "nx_crypto_ecdh.h"
#include "nx_crypto_dh.h"

static NX_CRYPTO_EC *curves[] = {
    (NX_CRYPTO_EC *)&_nx_crypto_ec_secp192r1, (NX_CRYPTO_EC *)&_nx_crypto_ec_secp224r1,
    (NX_CRYPTO_EC *)&_nx_crypto_ec_secp256r1, (NX_CRYPTO_EC *)&_nx_crypto_ec_secp384r1,
    (NX_CRYPTO_EC *)&_nx_crypto_ec_secp521r1,
};
static NX_CRYPTO_EC *mont_curves[] = {
    (NX_CRYPTO_EC *)&_nx_crypto_ec_x25519, (NX_CRYPTO_EC *)&_nx_crypto_ec_x448,
};

int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size) {
    if (size < 4) return -1;
    rd_t r = {data, size};
    uint8_t mode = rd_u8(&r) % 5;
    uint8_t sel = rd_u8(&r);
    uint32_t seed = rd_u8(&r) | (rd_u8(&r) << 8);
    srand(seed); /* the private keys generated by *_setup come from rand() */
    size_t got;

    if (mode == 0) { /* ECDSA verify */
        NX_CRYPTO_EC *curve = curves[sel % N_ELEMS(curves)];
        size_t hlen = rd_u8(&r) % 72, plen = rd_u8(&r) % 140, slen = rd_u8(&r) % 140;
        const uint8_t *h = rd_bytes(&r, hlen, &got); hlen = got;
        const uint8_t *p = rd_bytes(&r, plen, &got); plen = got;
        const uint8_t *s = rd_bytes(&r, slen, &got); slen = got;
        UCHAR *hash = dup_exact(h, hlen), *pub = dup_exact(p, plen), *sig = dup_exact(s, slen);
        HN_UBASE *scratch = (HN_UBASE *)calloc(1, NX_CRYPTO_ECDSA_SCRATCH_BUFFER_SIZE);
        _nx_crypto_ecdsa_verify(curve, hash, (UINT)hlen, pub, (UINT)plen, sig, (UINT)slen, scratch);
        free(scratch); free(sig); free(pub); free(hash);
    } else if (mode == 1) { /* ECDH, NIST curves */
        NX_CRYPTO_EC *curve = curves[sel % N_ELEMS(curves)];
        size_t rlen = rd_u8(&r) % 140;
        const uint8_t *rp = rd_bytes(&r, rlen, &got); rlen = got;
        UCHAR *remote = dup_exact(rp, rlen);
        NX_CRYPTO_ECDH *ecdh = (NX_CRYPTO_ECDH *)calloc(1, sizeof(*ecdh));
        UCHAR pub[140], secret[80];
        ULONG publen = 0, seclen = 0;
        if (_nx_crypto_ecdh_setup(ecdh, pub, sizeof(pub), &publen, curve, ecdh->nx_crypto_ecdh_scratch_buffer) ==
            NX_CRYPTO_SUCCESS)
            _nx_crypto_ecdh_compute_secret(ecdh, secret, sizeof(secret), &seclen, remote, (ULONG)rlen,
                                           ecdh->nx_crypto_ecdh_scratch_buffer);
        free(ecdh); free(remote);
    } else if (mode == 2) { /* ECDH, X25519 / X448 */
#ifdef NX_CRYPTO_ENABLE_CURVE25519_448
        NX_CRYPTO_EC *curve = mont_curves[sel % N_ELEMS(mont_curves)];
        size_t rlen = rd_u8(&r) % 72;
        const uint8_t *rp = rd_bytes(&r, rlen, &got); rlen = got;
        UCHAR *remote = dup_exact(rp, rlen);
        NX_CRYPTO_ECDH *ecdh = (NX_CRYPTO_ECDH *)calloc(1, sizeof(*ecdh));
        UCHAR pub[80], secret[80];
        ULONG publen = 0, seclen = 0;
        if (_nx_crypto_ecdh_setup_x25519_448(ecdh, pub, sizeof(pub), &publen, curve,
                                             ecdh->nx_crypto_ecdh_scratch_buffer) == NX_CRYPTO_SUCCESS)
            _nx_crypto_ecdh_compute_secret_x25519_448(ecdh, secret, sizeof(secret), &seclen, remote, (ULONG)rlen,
                                                      ecdh->nx_crypto_ecdh_scratch_buffer);
        free(ecdh); free(remote);
#else
        (void)mont_curves;
#endif
    } else if (mode == 3) { /* ECDH with an attacker-chosen private key import, then compute */
        NX_CRYPTO_EC *curve = curves[sel % N_ELEMS(curves)];
        size_t klen = rd_u8(&r) % 80, rlen = rd_u8(&r) % 140;
        const uint8_t *kp = rd_bytes(&r, klen, &got); klen = got;
        const uint8_t *rp = rd_bytes(&r, rlen, &got); rlen = got;
        UCHAR *priv = dup_exact(kp, klen), *remote = dup_exact(rp, rlen);
        NX_CRYPTO_ECDH *ecdh = (NX_CRYPTO_ECDH *)calloc(1, sizeof(*ecdh));
        UCHAR secret[80];
        ULONG seclen = 0;
        ecdh->nx_crypto_ecdh_curve = curve; /* the method-level SET_CURVE step */
        if (_nx_crypto_ecdh_key_pair_import(ecdh, curve, priv, (ULONG)klen, NULL, 0) == NX_CRYPTO_SUCCESS)
            _nx_crypto_ecdh_compute_secret(ecdh, secret, sizeof(secret), &seclen, remote, (ULONG)rlen,
                                           ecdh->nx_crypto_ecdh_scratch_buffer);
        free(ecdh); free(remote); free(priv);
    } else { /* finite-field DH, RFC 2409 group 2 */
        size_t rlen = rd_u8(&r) % 160;
        const uint8_t *rp = rd_bytes(&r, rlen, &got); rlen = got;
        UCHAR *remote = dup_exact(rp, rlen);
        NX_CRYPTO_DH *dh = (NX_CRYPTO_DH *)calloc(1, sizeof(*dh));
        HN_UBASE *scratch = (HN_UBASE *)calloc(1, NX_CRYPTO_DIFFIE_HELLMAN_SCRATCH_SIZE);
        UCHAR pub[NX_CRYPTO_DIFFIE_HELLMAN_MAX_KEY_SIZE + 8], secret[NX_CRYPTO_DIFFIE_HELLMAN_MAX_KEY_SIZE + 8];
        UINT publen = sizeof(pub);
        ULONG seclen = sizeof(secret);
        if (_nx_crypto_dh_setup(dh, pub, &publen, NX_CRYPTO_DH_GROUP_2, scratch) == NX_CRYPTO_SUCCESS)
            _nx_crypto_dh_compute_secret(dh, secret, &seclen, remote, (ULONG)rlen, scratch);
        free(scratch); free(dh); free(remote);
    }
    return 0;
}
